// Writes shared/icons.ml: the Lucide icons that CinePulse uses, as Yuka elements.
// Run with `npm run icons` after changing the list.
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { icons } = require("lucide");

const used = {
  home: "House",
  compass: "Compass",
  heart: "Heart",
  history: "History",
  search: "Search",
  tv: "Tv",
  chart: "ChartColumn",
  flame: "Flame",
  github: "Github",
  menu: "Menu",
  x: "X",
  star: "Star",
  plus: "Plus",
  check: "Check",
  play: "Play",
  chevron_left: "ChevronLeft",
  chevron_right: "ChevronRight",
  chevron_down: "ChevronDown",
  chevron_up: "ChevronUp",
  info: "Info",
  sparkles: "Sparkles",
  zap: "Zap",
  clock: "Clock",
  layout_grid: "LayoutGrid",
  list: "List",
  calendar: "Calendar",
  circle_check: "CircleCheck",
  share: "Share2",
  arrow_left: "ArrowLeft",
  skip_forward: "SkipForward",
  skip_back: "SkipBack",
  maximize: "Maximize2",
  minimize: "Minimize2",
  radio: "Radio",
  toggle_left: "ToggleLeft",
  toggle_right: "ToggleRight",
  film: "Film",
  user: "User",
  trash: "Trash2",
  bookmark: "Bookmark",
  trophy: "Trophy",
};

const str = (s) => JSON.stringify(String(s));
const node = ([tag, attrs]) =>
  `Yuka.element ${str(tag)} [ ${Object.entries(attrs)
    .map(([k, v]) => `Yuka.attr ${str(k)} ${str(v)}`)
    .join("; ")} ] []`;

let out = `(* Generated by scripts/icons.mjs from lucide ${require("lucide/package.json").version} (ISC license). *)

let svg cls children =
  Yuka.element "svg"
    [
      Yuka.attr "xmlns" "http://www.w3.org/2000/svg";
      Yuka.attr "viewBox" "0 0 24 24";
      Yuka.attr "fill" "none";
      Yuka.attr "stroke" "currentColor";
      Yuka.attr "stroke-width" "2";
      Yuka.attr "stroke-linecap" "round";
      Yuka.attr "stroke-linejoin" "round";
      Yuka.attr "aria-hidden" "true";
      Yuka.attr "class" cls;
    ]
    children
`;
for (const [name, lucide] of Object.entries(used)) {
  const nodes = icons[lucide];
  if (!nodes) throw new Error(`no lucide icon ${lucide}`);
  out += `\nlet ${name} cls = svg cls [ ${nodes.map(node).join("; ")} ]\n`;
}
process.stdout.write(out);
